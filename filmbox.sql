CREATE TEMP TABLE _h AS
SELECT u.id AS utilisateur_id, b.film_id, b.base,
       ('x' || substr(md5(u.id || '-' || b.film_id), 1, 8))::bit(32)::int AS h
FROM utilisateurs u CROSS JOIN _base b;

-- Environ 2 films sur 3 vus par chaque membre
INSERT INTO notes (utilisateur_id, film_id, note, note_le)
SELECT utilisateur_id, film_id,
       LEAST(5, GREATEST(0.5, ROUND((base + ((abs(h) % 11) - 5) * 0.15) * 2) / 2)),
       DATE '2026-01-05' + (abs(h / 7) % 255)
FROM _h
WHERE abs(h) % 3 <> 0;

-- Un visionnage par note, à la date de la note
INSERT INTO journal (utilisateur_id, film_id, date_visionnage)
SELECT utilisateur_id, film_id, note_le FROM notes;

-- Quelques revisionnages
INSERT INTO journal (utilisateur_id, film_id, date_visionnage)
SELECT n.utilisateur_id, n.film_id, n.note_le + 30 + (n.film_id % 20)
FROM notes n
WHERE n.note >= 4.5 AND n.note_le + 30 + (n.film_id % 20) <= DATE '2026-09-20';

